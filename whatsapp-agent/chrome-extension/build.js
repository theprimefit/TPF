// Packs the agent's own code (replies, scoring, follow-ups) into agent-bundle.js,
// so the extension can run the agent inside Chrome with no server.
// Run after changing src/ or config/: node chrome-extension/build.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const mods = { './store': 'src/store.js', './scoring': 'src/scoring.js', './brain': 'src/brain.js', './agent': 'src/agent.js' };

let out = `// Generated by chrome-extension/build.js from the agent's src/ files. Do not edit.
(() => {
const defs = {};
const cache = {};
function require(name) {
  if (cache[name]) return cache[name].exports;
  if (name === 'node:fs') return { existsSync: () => false };
  if (name === 'node:path') return { dirname: (p) => p };
  if (name === '@anthropic-ai/sdk') return function Anthropic() {};
  const module = (cache[name] = { exports: {} });
  defs[name](module, module.exports, require);
  return module.exports;
}
defs['./business.json'] = (module) => { module.exports = ${fs.readFileSync(path.join(root, 'config/business.json'), 'utf8').trim()}; };
`;
for (const [name, file] of Object.entries(mods)) {
  out += `defs['${name}'] = function (module, exports, require) {\n${fs.readFileSync(path.join(root, file), 'utf8')}\n};\n`;
}
out += `self.HLAgent = {
  business: require('./business.json'),
  createStore: require('./store').createStore,
  createRuleBrain: require('./brain').createRuleBrain,
  redFlag: require('./brain').redFlag,
  createAgent: require('./agent').createAgent,
};
})();
`;
fs.writeFileSync(path.join(__dirname, 'agent-bundle.js'), out);
console.log(`Wrote chrome-extension/agent-bundle.js (${Math.round(out.length / 1024)} KB)`);
